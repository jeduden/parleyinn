#!/bin/bash
# Finds the pull request to review and the head to review it at (ENG-21,
# ENG-28); writes number and head_sha to the step's outputs, or leaves
# the number empty when there is nothing to review.
#
# Run by .github/workflows/review.yml, which hands it its values in
# the environment; it takes the shell's default, no pipefail.
set -e

if [ "$EVENT" = issue_comment ]; then
  author=$(jq -r .comment.user.login "$GITHUB_EVENT_PATH")
  owners=$(gh api "repos/$REPO/contents/.github/CODEOWNERS" \
    -H 'Accept: application/vnd.github.raw' | grep -v '^#' \
    | grep -oE '@[A-Za-z0-9-]+(/[A-Za-z0-9_.-]+)?' | grep -v / | tr -d @ | sort -u)
  if ! printf '%s\n' "$owners" | grep -qxF "$author"; then
    echo "::notice::$author is no CODEOWNERS owner; nothing to review"
    exit 0
  fi
  if jq -e '.comment.body | split("\n") | map(select(test("\\S"))) | last // ""
    | test("^_Generated by \\[Claude Code\\]")' "$GITHUB_EVENT_PATH" > /dev/null; then
    echo "::notice::an agent's comment brings no review"
    exit 0
  fi
  pull=$(jq -r .issue.number "$GITHUB_EVENT_PATH")
  head=$(gh api "repos/$REPO/pulls/$pull" --jq \
    'select(.state == "open" and .draft == false and .head.repo.full_name == env.REPO) | .head.sha')
  if [ -z "$head" ]; then
    echo "::notice::pull request $pull is not open and ready from this repository; nothing to review"
    exit 0
  fi
  # The comment must come after the head it brings a review
  # of: a head committed later is not what the owner saw.
  commit_at=$(gh api "repos/$REPO/commits/$head" --jq .commit.committer.date)
  comment_at=$(jq -r .comment.created_at "$GITHUB_EVENT_PATH")
  if [[ $(date -d "$commit_at" +%s) -gt $(date -d "$comment_at" +%s) ]]; then
    echo "::notice::$head was committed after the comment; its CI run brings the review"
    exit 0
  fi
  passed=$(gh api "repos/$REPO/actions/workflows/ci.yml/runs?head_sha=$head&event=pull_request" \
    --jq '.workflow_runs | sort_by(.created_at) | last | .conclusion // empty')
  if [ "$passed" != success ]; then
    echo "::notice::CI has not passed on $head; its run brings the review"
    exit 0
  fi
else
  head=$RUN_HEAD
fi
number=$(HEAD_SHA=$head gh api "repos/$REPO/commits/$head/pulls" \
  --jq '[.[] | select(.state == "open" and .draft == false and .head.sha == env.HEAD_SHA)][0].number // empty')
if [ -z "$number" ]; then
  echo "::notice::no open, ready pull request has head $head; nothing to review"
fi
echo "number=$number" >> "$GITHUB_OUTPUT"
echo "head_sha=$head" >> "$GITHUB_OUTPUT"
