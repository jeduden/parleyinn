#!/bin/bash
# Collects what a CODEOWNERS owner in main wrote on the pull request into
# stakeholder-comments.json, dropping an agent's comment (ENG-21).
#
# Run by .github/workflows/review.yml, which hands it its values in
# the environment; it takes the shell's default, no pipefail.
set -e

owners=$(grep -v '^#' .github/CODEOWNERS \
  | grep -oE '@[A-Za-z0-9-]+(/[A-Za-z0-9_.-]+)?' | grep -v / \
  | tr -d @ | sort -u | jq -R . | jq -sc .)
{
  gh api --paginate "repos/$REPO/issues/$PULL/comments" \
    --jq '.[] | {author: .user.login, at: .created_at, body}'
  gh api --paginate "repos/$REPO/pulls/$PULL/reviews" \
    --jq '.[] | {author: .user.login, at: .submitted_at, body, state}'
} | jq -s --argjson owners "$owners" '[.[]
  | select(.author as $a | $owners | index($a))
  | select((.body // "") | test("\\S"))
  | select((.body | split("\n") | map(select(test("\\S"))) | last)
      | test("^_Generated by \\[Claude Code\\]") | not)]' \
  > stakeholder-comments.json
